def _read_rows() -> list[tuple[str, str]]:
    z = zipfile.ZipFile(XLSX)
    ss = ET.fromstring(z.read("xl/sharedStrings.xml"))
    strings: list[str] = []
    for si in ss.findall(f".//{{{NS}}}si"):
        strings.append("".join(t.text or "" for t in si.iter(f"{{{NS}}}t")))

    def col_row(cell_ref: str) -> tuple[int, int]:
        m = re.match(r"([A-Z]+)([0-9]+)", cell_ref)
        assert m
        col = 0
        for c in m.group(1):
            col = col * 26 + (ord(c) - ord("A") + 1)
        return col, int(m.group(2))

    sheet = ET.fromstring(z.read("xl/worksheets/sheet2.xml"))
    rows: dict[int, dict[int, str]] = {}
    for c in sheet.findall(f".//{{{NS}}}c"):
        r, t, v_el = c.get("r"), c.get("t"), c.find(f"{{{NS}}}v")
        if v_el is None or v_el.text is None:
            continue
        v = strings[int(v_el.text)] if t == "s" else v_el.text
        col, row = col_row(r)
        rows.setdefault(row, {})[col] = v

    data: list[tuple[str, str]] = []
    for row in sorted(rows.keys()):
        if row == 1:
            continue
        g = (rows[row].get(2) or "").strip()
        s = (rows[row].get(3) or "").strip()
        if not s:
            continue
        data.append((g, s))
    return data


