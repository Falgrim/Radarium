def _map_group_to_parent_slug() -> dict[str, str]:
    """XLSX в группе часто backslash, в pdef — слэш; даём оба варианта ключа."""
    m = _parent_slugs()
    d: dict[str, str] = {}
    for slug, title, kws, short in m:
        d[title] = slug
        if "/" in title:
            d[title.replace("/", "\\")] = slug
    return d


def main() -> None:
    rows_xlsx = _read_rows()
    pdefs = _parent_slugs()
    kids = _child_keywords()
    gslug = _map_group_to_parent_slug()
    title_by_pslug = {sl: t for sl, t, _, _ in pdefs}

    out: list[dict] = []
    for slug, title, kws, short in pdefs:
        out.append(
            {
                "slug": slug,
                "parent_slug": None,
                "title": title,
                "short_name": short,
                "group_title": title,
                "key_words": kws,
            }
        )

    for g_raw, s_raw in rows_xlsx:
        g = g_raw.strip()
        s = s_raw.strip()
        key = (g, s)
        if key not in kids:
            g2 = g.replace("/", "\\")
            s2 = s.replace("/", "\\")
            for kg, ks in ((g, s), (g2, s), (g, s2), (g2, s2), (g2, s2)):
                if (kg, ks) in kids:
                    key = (kg, ks)
                    break
            else:
                raise SystemExit(
                    f"Нет key_words для пары: G={g!r} S={s!r}\n"
                    f"  попробуйте добавить в _child_keywords"
                )
        slug, sname, kws = kids[key]
        pslug = (
            gslug.get(g)
            or gslug.get(g.replace("\\", "/"))
            or gslug.get(g.replace("/", "\\"))
        )
        if pslug is None:
            raise SystemExit(f"Неизвестная группа: {g!r}")
        out.append(
            {
                "slug": slug,
                "parent_slug": pslug,
                "title": s,
                "short_name": sname,
                "group_title": title_by_pslug[pslug],
                "key_words": kws,
            }
        )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps({"rows": out}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print("Wrote", OUT, "count", len(out))


if __name__ == "__main__":
    main()
