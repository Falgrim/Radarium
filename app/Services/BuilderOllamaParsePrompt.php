- performer_type: ровно одно из: индивидуал, бригада, работа с напарником, не указан. «сам/один» → индивидуал; «бригада/команда» → бригада; «с напарником/вдвоём» → работа с напарником.
- equipment_skills: инструмент и узкий навык, не больше 10. «ответственный», «пунктуальный» не включать. «болгарка» → УШМ, «перф» → перфоратор, «лазер» → лазерный уровень.
- legal_form: ровно одно из: СЗ, ИП, ООО, АО, другое, не указано.
