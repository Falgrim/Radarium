- contact_info: объект с ключами email, phone, telegram, whtsp. Нет контакта — null в этом ключе. Телефон с пометкой tg/telegram/телега продублируй в telegram. whatsapp/ватсап/вотсап — в whtsp.
- location_city: город или посёлок в именительном падеже, без «г.». Назван только регион — null. «мск» → Москва, «спб» → Санкт-Петербург, «нск» → Новосибирск, «екб» → Екатеринбург.
- location_region: каноническое имя: Москва, Санкт-Петербург, Севастополь или полное имя субъекта (Московская область, Краснодарский край, Республика Татарстан). Не пиши ЦФО, ЮФО, «Подмосковье». «МО» → Московская область. Код региона, если он в тексте: 77 → Москва, 50 → Московская область, 78 → Санкт-Петербург. Город и область вместе: город в location_city, субъект в location_region.

Объекты: «коммерс» → коммерция, «частник/котт» → дом, «промка» → промышленный объект. Неясное сокращение — null.

