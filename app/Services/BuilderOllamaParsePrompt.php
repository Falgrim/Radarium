Извлекай только то, что прямо сказано или однозначно следует из текста. Не додумывай. Нет данных — null. Пустая строка "" запрещена.

Правила type идут сверху вниз. Первое подходящее — окончательное, остальные не применяй.

1) "мусор" — не стройка; реклама товара; вопрос; флуд; спам (почти нет кириллицы, стена эмодзи, латинский набор). Кадровый аутсорс и рекрутинг, даже от первого лица: HR, подбор персонала, кадровое агентство, «закрою вакансию», «кадровый голод». Это не полевые работы. Автор предлагает сделать проект, документацию, чертёж или 3D-модель, а не монтировать, ремонтировать или отделывать на объекте: проектирование, проектировщик, архитектор, проектная документация, стадия ПД, стадия РД, AutoCAD, Revit, BIM-модель, 3D-модель, 3D-моделирование, визуализация, экспертиза проекта, МГЭ, 3ds Max, веб/UI-дизайн, behance. «Предлагаем услуги», «я архитектор», жилой комплекс, электроснабжение и «на стройке» это не отменяют. Монтаж или ремонт по готовому чертежу, ППР, ПТО и сметы — не этот пункт. Заказчик без самопрезентации исполнителя: «нужно/надо сделать», короткий заказ и «в лс», «кто свободен?», «есть кто на объект?» без описания своей бригады.
2) "вакансия" — автор набирает людей, а не предлагает свою работу. Маркеры: нужны/ищем/требуется/вакансия/откликнитесь; число людей; выход к часу или смена («к 17:00», «с 9 до 18», «на завтра», «график 5/2»); оплата найму за смену или за N часов («3300₽ (8 часов)»); «оплата по окончании/на карту»; просьба прислать в ЛС возраст, ФИО, телефон; «кто готов» вместе со сменой; «перекус дадут», «без обеда», «инструмент выдадут» при найме; сбор у метро или автобуса и время выхода; разовые погрузка, разгрузка, демонтаж с оплатой нанятым. ТЗ заказчика без «выполняем/ищем заказ/выезжаем»: шапка города, объём штуками («N колонн», «по X квадратов»), «туры есть», ставка «р/м²». «Ищем людей/мастера/бригаду», «требуются» и «бригада из N человек» как найм — тоже вакансия. Не путай с «мы готовы выехать» и «свободна бригада» у исполнителя.
3) "предложение услуги" — только если говорит исполнитель: я/мы, либо бригада/организация («бригада выполнит», «выполним», «оказываем услуги») и это физические работы на объекте (ремонт, монтаж, отделка, стройка). Проектирование, документация, чертёж, 3D-модель и резюме архитектора или проектировщика сюда не входят: их закрывает пункт 1. Сюда же резюме и «ищу работу/заказ/объект» от первого лица, «звоните нам», «наш прайс», если работа полевая. Поставка рабочих на объект (разнорабочие, монтажники, бригада выполнит работы) — это услуга, не кадровый пункт 1. Одно слово «бригада» или «мастер» без предложения выполнить работы — не этот пункт.
4) Сомнение между "предложение услуги" и "вакансия" — "вакансия". Любое другое сомнение — "мусор".

Если type = "мусор", остальные поля null, а specialities, object_types и equipment_skills — [].

Поля, если type не "мусор":
- service_type: короткая фраза из текста или null. Названия из каталога specialities сюда списком не копируй.
- specialities: только дословные строки из списка ниже, не больше 5. Нет подходящей — []. Не клади сюда типы объектов и слова не из списка.
